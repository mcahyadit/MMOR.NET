using System.IO;
using System.Text.Json;

namespace MMOR.Roslyn {
public partial class BakeJsonGenerator {
  internal readonly ref struct TraverseInfo {
    public readonly string current_type { get; init; }
    public readonly int object_depth { get; init; }
    public readonly ReadOnlySpan<ulong> container_metadata { get; init; }
  }

  internal static readonly JsonDocumentOptions kJdocOpts = new() {
    CommentHandling     = JsonCommentHandling.Skip,
    AllowTrailingCommas = true,
  };

  internal static string TranspileJson(BakedModel model, int idx, JsonSourceModel json) {
    using JsonDocument jdoc = JsonDocument.Parse(json.contents, kJdocOpts);
    JsonElement jroot       = jdoc.RootElement;

    StringBuilder sb = new();
    sb.Append("// <auto-generated/>\n");
    sb.Append("\nnamespace ").Append(model.nspace).Append(" {\n");

    string name = model.json_names[idx];

    if (model.kind == ModelKind.Interface) {
      sb.AppendFormat("public class {0} : {1} ", name, model.name).Append("{\n");
    } else {
      sb.Append("partial ");
      switch (model.kind) {
        case ModelKind.Class:
          sb.Append("class");
          break;
        case ModelKind.Struct:
          sb.Append("struct");
          break;
        case ModelKind.Record:
          sb.Append("record");
          break;
      }
      sb.Append(' ').Append(model.name).Append(" {\n");
      sb.Append("public static readonly ").Append(model.name).Append(' ').Append(name);
      sb.Append(" = new ").Append(model.name).Append(" {\n");
    }

    for (int i = 0; i < model.properties.Length; ++i) {
      PropertyModel property = model.properties[i];
      bool prop_exists       = jroot.TryGetProperty(property.name, out JsonElement value);
      TraverseInfo info      = new TraverseInfo {
        current_type       = property.type,
        object_depth       = 0,
        container_metadata = property.container_metadata.AsSpan(),
      };
      if (model.kind == ModelKind.Interface) {
        sb.AppendFormat("  public {0} {1} = ", property.type, property.name);

        if (prop_exists) {
          sb.Append(" { get; } = ");
          switch (value.ValueKind) {
            case JsonValueKind.Object:
              TranspileDictionary(sb, value, info);
              break;
            case JsonValueKind.Array:
              TranspileArray(sb, value, info);
              break;
            default:
              sb.Append(TranspileGeneric(value));
              break;
          }
        } else {
          sb.Append(" => throw new System.NotImplementedException()");
        }
        sb.Append(";\n\n");
      } else if (prop_exists) {
        info = info with { object_depth = info.object_depth + 1 };
        sb.AppendFormat("  {0} = ", property.name);
        switch (value.ValueKind) {
          case JsonValueKind.Object:
            TranspileDictionary(sb, value, info);
            break;
          case JsonValueKind.Array:
            TranspileArray(sb, value, info);
            break;
          default:
            sb.Append(TranspileGeneric(value));
            break;
        }
        sb.Append(",\n");
      }
    }

    if (model.kind != ModelKind.Interface) {
      sb.Append('}').AppendFormat(";  // {0}\n", name);
      sb.Append('}').AppendFormat(" // {0}\n", model.name);
    } else {
      sb.Append('}').AppendFormat("  // {0}\n", name);
    }
    sb.Append('}').AppendFormat(" // {0}\n", model.nspace);
    return sb.ToString();
  }

  public static string TranspileGeneric(in JsonElement element) {
    return element.ValueKind switch {
      JsonValueKind.Number => element.GetRawText(),
      JsonValueKind.True   => "true",
      JsonValueKind.False  => "false",
      JsonValueKind.Null   => "null",
      JsonValueKind.String => $"\"{element.GetString()}\"",
      _                    => $"\"{element.GetRawText()}\"",
    };
  }

  public static string GenericType(in string container) {
    if (container.EndsWith("[]")) {
      return container[..^ 2];
    } else {
      return container[(container.IndexOf('<') + 1)..^ 1];
    }
  }

  public static void GetDictTypes(string dict_type, out string key_type, out string val_type) {
    string generic = GenericType(dict_type);
    int idx        = generic.IndexOf(',');
    key_type       = generic[..idx];
    val_type       = generic[(idx + 1)..];
  }

  internal static void TranspileDictionary(StringBuilder sb, in JsonElement element,
      in TraverseInfo info) {
    sb.AppendFormat("new {0} ", info.current_type).Append('{');

    string indent   = new(' ', info.object_depth * 2);
    ulong cont_meta = info.container_metadata[0];

    GetDictTypes(info.current_type, out string enum_name, out string val_type);
    foreach (JsonProperty prop in element.EnumerateObject()) {
      sb.AppendFormat("\n    {0}", indent);
      // Transpile Key
      if ((cont_meta & kDictKeyStr) != 0) {
        sb.AppendFormat("[\"{0}\"] = ", prop.Name);
      } else if ((cont_meta & kDictKeyChar) != 0) {
        sb.AppendFormat("['{0}'] = ", prop.Name);
      } else if ((cont_meta & kDictKeyEnum) != 0) {
        sb.Append('[');
        bool first      = true;
        string[] splits = prop.Name.Split(',');
        foreach (string split in splits) {
          if (first) {
            first = false;
          } else {
            sb.Append(" | ");
          }
          sb.Append(enum_name).Append('.').Append(split);
        }
        sb.Append("] = ");
      } else {
        sb.AppendFormat("[{0}] = ", prop.Name);
      }

      // Transpile Value
      if (prop.Value.ValueKind == JsonValueKind.Array) {
        TranspileArray(sb, prop.Value,
            info with {
              current_type       = val_type,
              object_depth       = info.object_depth + 1,
              container_metadata = info.container_metadata[1..],
            });
      } else if (prop.Value.ValueKind == JsonValueKind.Object) {
        TranspileDictionary(sb, prop.Value,
            info with {
              current_type       = val_type,
              object_depth       = info.object_depth + 1,
              container_metadata = info.container_metadata[1..],
            });
      } else {
        sb.Append(TranspileGeneric(prop.Value));
      }
      sb.Append(',');
    }
    sb.AppendFormat("\n  {0}", indent).Append('}');
  }

  internal static void TranspileArray(StringBuilder sb, in JsonElement element,
      in TraverseInfo info) {
    sb.AppendFormat("new {0} ", info.current_type).Append('{');

    string val_type = GenericType(info.current_type);
    string indent   = new(' ', info.object_depth * 2);
    foreach (JsonElement value in element.EnumerateArray()) {
      if (value.ValueKind == JsonValueKind.Array) {
        sb.Append('\n');
        TranspileArray(sb, value,
            info with {
              current_type = val_type,
              object_depth = info.object_depth + 1,
            });
      } else if (value.ValueKind == JsonValueKind.Object) {
        sb.Append('\n');
        TranspileDictionary(sb, value,
            info with {
              current_type       = val_type,
              object_depth       = info.object_depth + 1,
              container_metadata = info.container_metadata[1..],
            });
      } else {
        sb.Append(TranspileGeneric(value));
      }
      sb.Append(',');
    }
    sb.Append("}");
  }
}
}
